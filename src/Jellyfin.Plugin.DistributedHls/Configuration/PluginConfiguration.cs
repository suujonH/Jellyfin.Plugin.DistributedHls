using MediaBrowser.Model.Plugins;

namespace Jellyfin.Plugin.DistributedHls.Configuration;

public sealed class PluginConfiguration : BasePluginConfiguration
{
    public bool Enabled { get; set; }
    public bool AllowLocalOriginal { get; set; }
    public Guid[] OriginalUsers { get; set; } = [];
    // Empty means every library.
    public Guid[] Libraries { get; set; } = [];
    public int[] Qualities { get; set; } = [1080, 720, 480];
    public string OutputPath { get; set; } = OperatingSystem.IsWindows() ? Path.Combine(Path.GetTempPath(), "hls") : "/cache/hls";
    public int LeaseMinutes { get; set; } = 5;
    public int PlaybackTokenHours { get; set; } = 24;
    public bool VerifyModifiedTime { get; set; } = true;
    public int OrphanRetentionHours { get; set; } = 72;
    public int MaxAttempts { get; set; } = 3;
    // Base64 HMAC key of the playback grants; generated by Plugin and never shown on the settings page.
    public string PlaybackSigningKey { get; set; } = "";
}
